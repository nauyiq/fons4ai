package com.fons.cloud.reactor.api;

import reactor.core.publisher.Flux;
import reactor.core.publisher.Mono;

/**
 * 一次响应式执行的通用运行协议。
 *
 * <p>该契约只描述不同执行领域共有的运行能力：运行标识、状态快照、过程事件、
 * 结构化收口结果和取消。普通任务、Agent 或其他执行框架通过特化事件、结果和状态
 * 接入该协议，通用层不解释具体领域状态。</p>
 *
 * <p>事件流、收口结果、状态和取消操作必须属于同一次运行。实现必须保证订阅
 * {@link #events()} 或 {@link #completion()} 时只会触发同一个执行实例，并且底层执行最多
 * 启动一次。</p>
 *
 * @param <E> 本次运行发布的过程事件类型
 * @param <R> 本次可观察执行分段的结构化收口结果类型
 * @param <S> 本次运行所属领域的状态类型
 * @author hongqy
 */
public interface ReactiveRun<E, R, S> {

    /**
     * 获取本次运行的唯一标识。
     *
     * @return 在本次运行生命周期内保持不变的非空运行标识
     */
    String runId();

    /**
     * 获取当前运行状态。
     *
     * <p>该方法返回瞬时状态快照。状态的取值、流转规则以及终态判断由具体领域负责。</p>
     *
     * @return 当前运行状态
     */
    S state();

    /**
     * 获取本次运行的过程事件流。
     *
     * <p>事件流只承载过程事件，不以最后一个事件代替结构化收口结果。实现可以采用单播、
     * 多播或回放策略，具体策略应由实现模块声明；调用方不得默认事件可重放。</p>
     *
     * <p>事件通道必须在当前执行分段的 {@link #completion()} 发出收口信号前结束。
     * 事件通道的错误只表示过程流已结束，不得取代结构化收口结果。</p>
     *
     * @return 与本次运行绑定的非空事件流
     */
    Flux<E> events();

    /**
     * 获取本次可观察执行分段的权威结构化收口结果。
     *
     * <p>结果对象可以表达业务成功、业务失败、暂停或取消等领域结果。
     * 只有实现无法形成结构化结果时，才使用错误信号收口。因此调用方不得把
     * {@code onNext} 等同于领域成功。</p>
     *
     * <p>该 Mono 与 {@link #events()} 共享同一次启动门禁和取消边界。实现必须向
     * 多个订阅者以及终止后的晚订阅者重放同一个结果或错误，新增订阅者不得重新启动
     * 底层执行。对可恢复运行而言，该结果可以是当前执行分段的暂停结果，不必是整个运行的
     * 不可逆终态。</p>
     *
     * @return 与本次运行绑定的非空收口信号
     */
    Mono<R> completion();

    /**
     * 请求取消本次运行。
     *
     * <p>取消应向运行时管理的根订阅和已接入的独立子运行传播。重复调用必须幂等，已完成
     * 运行的具体返回语义由实现模块声明。</p>
     *
     * @return {@code true} 表示取消请求已被接受或此前已经接受；{@code false} 表示无法接受
     */
    boolean cancel();
}
