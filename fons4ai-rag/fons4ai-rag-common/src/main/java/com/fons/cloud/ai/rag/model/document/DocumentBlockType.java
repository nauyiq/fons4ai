package com.fons.cloud.ai.rag.model.document;

/**
 * 解析文档中的内容块类型。
 *
 * @author hongqy
 */
public enum DocumentBlockType {

    /**
     * 文档级标题，不是从文件名推断出的显示名称。
     */
    TITLE,
    /**
     * 具有实际层级的章节标题，正文归属通过 DocumentBlock 的父节点表达。
     */
    HEADING,
    /**
     * 已确认的工作表、幻灯片、数据区域或记录集合，复用结构父级，不把组名自动放入正文。
     */
    GROUP,
    /**
     * 普通正文段落，可在所属结构范围内继续进行文本切分。
     */
    PARAGRAPH,
    /**
     * 已识别的列表条目，不因格式分类而自行推断列表结构。
     */
    LIST_ITEM,
    /**
     * 持有 TableContent 的结构化表格，不能按普通正文随意拆分单元格。
     */
    TABLE,
    /** 一条具有实际字段/节点树的对象记录，不是任意 JSON 字符串。 */
    RECORD,
    /**
     * 引用文档内图片资源的内容单元，本身不代表已完成 OCR 或图片描述生成。
     */
    IMAGE,
    /**
     * 解析器确认的代码内容，不代表已完成语言识别或语法分块。
     */
    CODE,
    /**
     * 解析器确认的公式内容，分块时需由支持该类内容的实现处理。
     */
    FORMULA,
    /**
     * 已确认的分页标记，不自动成为所有分块策略的强制边界。
     */
    PAGE_BREAK,
    /**
     * 实际获得的媒体转写文本；时间或其他来源信息只能采用已确认事实。
     */
    TRANSCRIPT
}
